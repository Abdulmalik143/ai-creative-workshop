"""Convert the Wamda reference video into pixel-art sprite data (palette-indexed, nibble-packed, base64).
Usage: python make-wamda-sprites.py <Wamda.mp4> <out.ts> [preview.png]
"""
import sys, subprocess, base64, os, tempfile, json
import numpy as np
from PIL import Image
from scipy import ndimage

SRC, OUT = sys.argv[1], sys.argv[2]
PREVIEW = sys.argv[3] if len(sys.argv) > 3 else None
W, H = 72, 76           # sprite canvas
SCALE_W, SCALE_H = 70, 76
# clips are lists of source-frame indices i (the video is sampled every 4th frame: n = 4*i)
CLIPS = {
    "idle":  [0, 1, 2, 3],
    "run":   [7, 8, 9, 10, 12, 13, 14, 15, 16, 17],
    "wave":  [20, 21, 20, 22],
    "shrug": [40, 41],
    "think": [45, 47],
    "lookR": [56, 57, 58],
    "lookL": [66, 67, 68, 69, 70],
    "hop":   [26, 27, 28],
}
tmp = tempfile.mkdtemp()
subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", SRC, os.path.join(tmp, "f%03d.png")], check=True)

def load(i):
    n = 4 * i + 1  # ffmpeg numbers from 1
    im = Image.open(os.path.join(tmp, f"f{n:03d}.png")).convert("RGB")
    a = np.asarray(im).astype(np.int32)
    near_white = a.min(axis=2) > 226
    lab, _ = ndimage.label(near_white)
    border = set(np.unique(np.concatenate([lab[0], lab[-1], lab[:, 0], lab[:, -1]]))) - {0}
    bg = np.isin(lab, list(border))
    alpha = (~bg).astype(np.uint8) * 255
    # fill tiny holes so the figure is one solid mass
    alpha = ndimage.binary_closing(alpha > 0, iterations=1).astype(np.uint8) * 255
    rgba = np.dstack([a.astype(np.uint8), alpha])
    img = Image.fromarray(rgba, "RGBA")
    # premultiplied box downscale, so edges don't bleed white
    arr = np.asarray(img).astype(np.float32)
    arr[..., :3] *= arr[..., 3:4] / 255.0
    pm = Image.fromarray(arr.astype(np.uint8), "RGBA").resize((SCALE_W, SCALE_H), Image.BOX)
    p = np.asarray(pm).astype(np.float32)
    al = p[..., 3:4] / 255.0
    rgb = np.where(al > 0, p[..., :3] / np.maximum(al, 1e-4), 0)
    out_rgb = np.zeros((H, W, 3), np.float32)
    out_a = np.zeros((H, W), np.float32)
    x0 = (W - SCALE_W) // 2
    out_rgb[:, x0:x0 + SCALE_W] = rgb
    out_a[:, x0:x0 + SCALE_W] = al[..., 0]
    return np.clip(out_rgb, 0, 255).astype(np.uint8), out_a > 0.5

need = sorted({i for c in CLIPS.values() for i in c})
frames = {i: load(i) for i in need}

# a fixed palette read off the character: outline, jacket greys, headphone/sole whites, the orange family
pal = np.array([
    (0x0a, 0x0a, 0x0c), (0x17, 0x17, 0x1b), (0x2a, 0x2a, 0x31), (0x46, 0x46, 0x4f),
    (0x8d, 0x8d, 0x96), (0xe9, 0xe9, 0xea),
    (0x9a, 0x3f, 0x08), (0xe5, 0x68, 0x0a), (0xff, 0x8a, 0x1a), (0xff, 0xb2, 0x5e),
], np.uint8)

def index_frame(rgb, mask):
    d = ((rgb[:, :, None, :].astype(np.int32) - pal[None, None, :, :].astype(np.int32)) ** 2).sum(-1)
    idx = (d.argmin(-1) + 1).astype(np.uint8)
    idx[~mask] = 0
    # drop isolated stray pixels (alpha) and recolour isolated colour specks with their commonest neighbour
    m = idx > 0
    nb = ndimage.convolve(m.astype(np.int32), np.ones((3, 3), np.int32), mode="constant") - m
    idx[(m) & (nb < 2)] = 0
    out = idx.copy()
    for y in range(1, idx.shape[0] - 1):
        for x in range(1, idx.shape[1] - 1):
            v = idx[y, x]
            if v == 0:
                continue
            win = idx[y - 1:y + 2, x - 1:x + 2].reshape(-1)
            win = np.delete(win, 4)
            if (win == v).sum() == 0:
                nz = win[win > 0]
                if len(nz):
                    out[y, x] = np.bincount(nz).argmax()
    return out

def pack(idx):
    flat = idx.reshape(-1)
    if len(flat) % 2:
        flat = np.append(flat, 0)
    b = (flat[0::2] << 4) | flat[1::2]
    return base64.b64encode(b.astype(np.uint8).tobytes()).decode()

data = {}
sheet = []
for name, lst in CLIPS.items():
    data[name] = []
    for i in lst:
        idx = index_frame(*frames[i])
        data[name].append(pack(idx))
        sheet.append(idx)

hexes = ["#%02x%02x%02x" % tuple(c) for c in pal]
ts = "// generated by scripts/make-wamda-sprites.py from the Wamda reference video. Do not edit by hand.\n"
ts += f"export const WAMDA_W = {W};\nexport const WAMDA_H = {H};\n"
ts += f"export const WAMDA_PALETTE = {json.dumps(hexes)};\n"
ts += "/** frames are nibble-packed palette indices (0 = transparent), base64 */\n"
ts += "export const WAMDA_CLIPS: Record<string, string[]> = " + json.dumps(data) + ";\n"
open(OUT, "w").write(ts)
print("palette", hexes)
print("frames", sum(len(v) for v in data.values()), "bytes", len(ts))

if PREVIEW:
    cols = 12
    rows = (len(sheet) + cols - 1) // cols
    S = 3
    img = Image.new("RGB", (cols * W * S, rows * H * S), (40, 44, 48))
    colors = np.vstack([[0, 0, 0], pal])
    for k, idx in enumerate(sheet):
        rgb = colors[idx].astype(np.uint8)
        im = Image.fromarray(rgb).resize((W * S, H * S), Image.NEAREST)
        m = Image.fromarray(((idx > 0) * 255).astype(np.uint8)).resize((W * S, H * S), Image.NEAREST)
        img.paste(im, ((k % cols) * W * S, (k // cols) * H * S), m)
    img.save(PREVIEW)
